// Зачем этот файл вообще существует: при портировании net_driver.cpp с
// virtio-net на GENET (Фаза 3.2, ROADMAP.md) аппаратная граница была
// сознательно вынесена в маленький интерфейс (net_hw_init/send/poll_rx/
// rx_done, см. net_driver.cpp) — вся протокольная логика (ARP/IPv4/UDP/
// DNS/SNTP-клиент, диспетчер команд шелла) обращается ТОЛЬКО через него,
// не трогая регистры GENET напрямую. Если этот же интерфейс реализовать
// поверх Wi-Fi-чипа, вся эта протокольная логика заработает без единой
// правки — именно это имелось в виду под "базой под будущий wifi".
//
// === Почему сам Wi-Fi не написан в этой сессии ===
//
// На RPi4 Wi-Fi — это BCM43455 (Cypress/Broadcom), подключённый ОТДЕЛЬНЫМ
// SDIO-хостом (DT: /soc/mmcnr@7e300000, "brcm,bcm2835-mmc", SD1,
// non-removable — см. RPI4_WIFI_SDIO_PADDR/SIZE/IRQ в h/platform.h). Это
// НЕ тот же контроллер, что EMMC2 (blk_driver.cpp) — SDIO-протокол похож на
// SD (CMD/response, как в blk_driver.cpp), но поверх него живёт совершенно
// другой, специфичный для Broadcom протокол ("brcmfmac" в Linux):
//
//   1. Сначала обычная SDIO-инициализация карты (CMD0/CMD5/CMD3/CMD7 —
//      похоже на blk_driver.cpp, но SDIO, не SD memory card).
//   2. Загрузка ПРОПРИЕТАРНОЙ прошивки чипа (файл вида
//      brcmfmac43455-sdio.bin, десятки-сотни KB) через SDIO — сам чип без
//      неё нерабочая железка, прошивку нужно откуда-то достать (обычно
//      идёт в комплекте firmware-blob'ов Raspberry Pi OS) и разместить
//      на нашем FAT-разделе, читать через уже готовый blk_driver.cpp.
//   3. Загрузка NVRAM-конфигурации (brcmfmac43455-sdio.txt) — калибровочные
//      данные конкретного модуля антенны/платы.
//   4. Протокол "CDC/BDC" поверх SDIO для IOCTL-команд (сканирование сетей,
//      WPA2-хендшейк, ассоциация с точкой доступа, отправка/приём кадров)
//      — это отдельный, нетривиальный протокол, на порядок сложнее и
//      GENET, и EMMC2 вместе взятых.
//
// Итого: это отдельный большой проект (реалистично — недели, не часы),
// требующий вдобавок поиска/лицензирования прошивки. Сознательно оставлено
// на будущее отдельным заходом, а не встроено "заодно" в Фазу 3.2.
//
// === Как будущий Wi-Fi-бэкенд подключился бы ===
//
// Ровно та же четвёрка функций, что уже реализована для GENET в
// net_driver.cpp (см. её komментарии и h/platform.h GENET_* для образца
// стиля регистровых пойков):
//
//   bool wifi_hw_init(seL4_CPtr console_ep);
//   bool wifi_hw_send(const void* frame, uint32_t len);
//   bool wifi_hw_poll_rx(uint8_t** out_frame, uint32_t* out_len);
//   void wifi_hw_rx_done();
//
// Открытый вопрос на тот момент (не решается сейчас): либо net_driver.cpp
// получает рантайм-переключатель "GENET или Wi-Fi" (например, пробовать
// GENET, при отсутствии линка — падать на Wi-Fi), либо Wi-Fi становится
// отдельным процессом (wifi_driver) с тем же IPC-контрактом (BOOT_NET_EP и
// т.д.), который может заменить net_driver целиком или работать параллельно
// как второй сетевой интерфейс — решать по ситуации, когда/если до этого
